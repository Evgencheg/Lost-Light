using System.IO;
using Content.Shared._WL.ScreenCapture;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._WL.ScreenCapture.UI;

[GenerateTypedNameReferences]
public sealed partial class ImageUi : DefaultWindow
{
    public ImageUi()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetImage(byte[] imageData, string playerName, PhotoCaptureType type)
    {
        var typeName = Loc.GetString(type == PhotoCaptureType.Clyde
            ? "screen-capture-type-clyde"
            : "screen-capture-type-viewport");

        Title = Loc.GetString("image-window-title-player", ("player", playerName), ("type", typeName));

        try
        {
            using var stream = new MemoryStream(imageData);
            ImageDislay.Texture = Texture.LoadFromPNGStream(stream);
        }
        catch
        {
            Title = Loc.GetString("screen-capture-error-decode");
        }
    }
}
