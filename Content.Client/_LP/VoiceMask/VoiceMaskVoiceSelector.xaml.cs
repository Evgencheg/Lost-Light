using System.Linq;
using Content.Client._Starlight.Lobby.UI;
using Content.Client._Starlight.TextToSpeech;
using Content.Shared._LP.VoiceMask;
using Content.Shared._Starlight.TextToSpeech;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._LP.VoiceMask;

/// <summary>
/// Выбор голоса TTS в окне голосовой маски. Список голосов тот же, что при создании персонажа.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class VoiceMaskVoiceSelector : BoxContainer
{
    [Dependency] private IPrototypeManager _prototype = default!;
    [Dependency] private IEntityManager _entMan = default!;

    private VoiceSelectorWindow? _window;
    private string? _voice;

    public event Action<string?>? OnVoiceChange;

    public VoiceMaskVoiceSelector()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        VoiceButton.OnPressed += _ => OpenWindow();
        ResetButton.OnPressed += _ => OnVoiceChange?.Invoke(null);
        UpdateButton();
    }

    public void SetVoice(string? voice)
    {
        _voice = voice;
        UpdateButton();

        if (_window != null && voice != null && _prototype.TryIndex<VoicePrototype>(voice, out var proto))
            _window.SelectVoice(proto);
    }

    private void OpenWindow()
    {
        if (_window == null)
        {
            var voices = _prototype.EnumeratePrototypes<VoicePrototype>()
                .Where(VoiceMaskTtsVoices.IsAllowed)
                .ToList();

            _window = new VoiceSelectorWindow(voices);
            _window.OnVoiceSelected += voice => OnVoiceChange?.Invoke(voice.ID);
            _window.OnPreviewRequested += () =>
            {
                if (_window.CurrentVoice != null)
                    _entMan.System<TextToSpeechSystem>().RequestPreviewTts(_window.CurrentVoice.ID);
            };

            if (_voice != null && _prototype.TryIndex<VoicePrototype>(_voice, out var current))
                _window.SelectVoice(current);
        }

        _window.OpenCentered();
    }

    private void UpdateButton()
    {
        VoiceButton.Text = _voice != null && _prototype.TryIndex<VoicePrototype>(_voice, out var proto)
            ? Loc.GetString(proto.Name)
            : Loc.GetString("voice-mask-name-change-tts-voice-default");
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();
        _window?.Close();
        _window = null;
    }
}
